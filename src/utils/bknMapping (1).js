// บก.น. -> [สน. ในสังกัด] สร้างอัตโนมัติจาก STATION_TO_BKN
export const BKN_TO_STATIONS = Object.entries(STATION_TO_BKN).reduce(
  (acc, [station, bkn]) => {
    if (!acc[bkn]) acc[bkn] = []
    acc[bkn].push(station)
    return acc
  },
  {}
)

// คืนรายชื่อ สน. ในสังกัด บก.น. ที่ระบุ (คืน [] ถ้าไม่พบ)
export function getStations(bkn) {
  return BKN_TO_STATIONS[bkn] || []
}
