// แปลงชื่อเขต -> บก.น. (รองรับทั้ง "เขตคลองเตย" และ "คลองเตย")
// หมายเหตุ: data จริงสะกด "เขตราษฏร์บูรณะ" (ฏ) — normalize เป็น "ราษฎร์บูรณะ" (ฎ)
export function getBknByDistrict(district) {
  if (!district) return 'ไม่ระบุ'
  let d = String(district).trim().replace(/^เขต\s*/, '')
  if (d === 'ราษฏร์บูรณะ') d = 'ราษฎร์บูรณะ'
  return DISTRICT_TO_BKN[d] || 'ไม่ระบุ'
}

