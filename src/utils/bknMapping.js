export const BKN_TO_DISTRICTS = {}
for (const [d, b] of Object.entries(DISTRICT_TO_BKN)) {
  if (!BKN_TO_DISTRICTS[b]) BKN_TO_DISTRICTS[b] = []
  BKN_TO_DISTRICTS[b].push(d)
}
// คืนรายชื่อเขต (มีคำนำหน้า "เขต") ของ บก.น. ที่ระบุ
export function getDistricts(bkn) {
  return (BKN_TO_DISTRICTS[bkn] || []).map(d => `เขต${d}`)
}

